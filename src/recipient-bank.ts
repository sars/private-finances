export interface RecipientBank {
  bankCode: string;
  bankName: string | null;
  source: 'IBAN bank code';
  registrySource: string;
  registryRetrievedAt: string;
}

/** Call only with the provider's counterparty IBAN, never the owner's account. */
export function recipientBankFromIban(value: unknown): RecipientBank | null {
  if (typeof value !== 'string' || value.length > 64) return null;
  const iban = value.replace(/\s/g, '').toUpperCase();
  if (!/^UA\d{27}$/.test(iban)) return null;
  // ISO 13616 checksum, calculated incrementally without floating-point overflow.
  const rearranged = iban.slice(4) + '3010' + iban.slice(2, 4);
  let remainder = 0;
  for (const digit of rearranged)
    remainder = (remainder * 10 + Number(digit)) % 97;
  if (remainder !== 1) return null;
  const bankCode = iban.slice(4, 10);
  return {
    bankCode,
    bankName: ukrainianBanks[bankCode] ?? null,
    source: 'IBAN bank code',
    registrySource: recipientBankRegistry.source,
    registryRetrievedAt: recipientBankRegistry.retrievedAt,
  };
}

/** Accept only a masked PAN explicitly supplied for the counterparty.
 * This does not identify an issuing bank; no BIN service receives card data.
 */
export function recipientCardNetwork(
  value: unknown,
): 'Visa' | 'Mastercard' | null {
  if (typeof value !== 'string' || value.length > 40) return null;
  const pan = value.replace(/[ -]/g, '');
  if (!/^(?=[0-9*xX•]{13,19}$)(?=.*[*xX•])[0-9]+[*xX•]+[0-9]*$/.test(pan))
    return null;
  if (pan.startsWith('4')) return 'Visa';
  if (/^5[1-5]/.test(pan)) return 'Mastercard';
  const prefix = pan.slice(0, 4);
  if (
    /^\d{4}$/.test(prefix) &&
    Number(prefix) >= 2221 &&
    Number(prefix) <= 2720
  )
    return 'Mastercard';
  return null;
}
